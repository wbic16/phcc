#!/usr/bin/env python3
"""build_reissue.py — stage 1 of the F1/F4 receipt re-issue:
from the catch-up phext (54ab8532...) build the pre-Design,
pre-receipts stage:

  * lib/libtcc1.c Vol 2 Source scroll -> repo F1 bytes (69879e2a...);
    Slice 0 manifest (Sec 1) sha/size spliced; Vol 3 replaced from
    the importer pipeline output (work/vol3_libtcc1.json); rebind
    manifest + degradation register lines spliced (importer method).
  * phext/phext.c + phext/phext.h Source scrolls -> repo F4 bytes
    (cfdab3fd... / 144653da...); Sec 14 addendum lines updated.
  * Library-10000 region: phext.o scroll replaced (canonical
    phext-binary:1:base64 of the F4-built object); the four libtcc1
    scrolls re-encoded from the F1-built objects and asserted
    byte-identical (F1 changes no emitted code); root manifest
    provenance updated (compiler strings, commit e399b212, built-at;
    phext entry raw size/sha).
  * Three assembly listings regenerated (fresh provenance; libtcc1
    bodies asserted identical to the previous listings' bodies).
  * Build register (Meta Sec 15): compiler lines/commit/built-at.

Everything else byte-identical to the base — asserted scroll-diff.
Output: work/stage1.phext. Receipts (Proofs), the Design view, the
Sec 6 note and the Sec 22 resolution are the assemble step; the
gate verdict is regenerated by gate v8.1.0, never written here.
"""
import base64
import hashlib
import json
import os
import sys

WS = os.path.expanduser("~/workspace")
sys.path.insert(0, os.path.join(WS, "phcc-reissue/tools"))
import phext_io

R = os.path.join(WS, "phcc-reissue")
BASE = os.path.join(WS, "phcc-catchup/phcc.phext")
FIXED = os.path.join(WS, "phcc-attrfix/tree")
OUT = os.path.join(R, "work/stage1.phext")

OLD1 = "0e2eb64bc4607db08846a82df5d4f03ff3f0ce19f568bbf4db9a9729b8a9d630"
NEW1 = "69879e2a6117abe1dba7ddcf5539d9b816f18bea3e80452b96c1c0c991069aab"
COMMIT = "e399b212271b7e1277371b4b7ac6a34095e13363"
CC_X86 = "tcc version 1.0.0 2026-11-07 attrfix@e399b212 (x86_64 Linux)"
CC_ARM = "tcc version 1.0.0 2026-11-07 attrfix@e399b212 (AArch64 Linux)"
BUILT_AT = "2026-11-07T11:57:28-06:00"
HOST = "aletheia-core"
XFLAGS = ("-Wall -O2 -Wdeclaration-after-statement -Wno-unused-result "
          "-fPIC -fno-omit-frame-pointer -Wno-unused-function "
          "-Wno-unused-variable")
RENDER_X86 = "GNU objdump (GNU Binutils for Ubuntu) 2.42"
RENDER_ARM = "llvm-objdump-18 (Ubuntu LLVM version 18.1.3)"

LIBTCC1_SRC = (1, 1, 1, 4, 2, 7, 1, 2, 1)
PHEXTC_SRC = (1, 1, 1, 4, 2, 10, 10, 1, 1)
PHEXTH_SRC = (1, 1, 1, 4, 2, 10, 10, 2, 1)


def sha(b):
    return hashlib.sha256(b).hexdigest()


def splice_block(lines, path, new_lines):
    idx = [i for i, l in enumerate(lines) if l.startswith(path + "\t")]
    assert idx, f"no lines for {path}"
    assert idx == list(range(idx[0], idx[-1] + 1)), f"{path} lines not contiguous"
    return lines[:idx[0]] + new_lines + lines[idx[-1] + 1:]


def normalize_listing(body, objname):
    text = body.decode("utf-8")
    lines = text.split("\n")
    for i, line in enumerate(lines[:3]):
        if "file format" in line:
            idx = line.index(objname)
            lines[i] = line[idx:]
            break
    return "\n".join(lines).encode("utf-8")


def assembly_scroll(artifact, src_coord, src_sha, target, compiler, cmd,
                    flags, renderer, render_cmd, obj_coord, obj_raw,
                    listing_body, obj_name):
    body = normalize_listing(listing_body, obj_name)
    hdr = [
        "GENERATED — phcc generated assembly (builds pass). Machine-owned "
        "scroll; regenerated from source + object, never hand-edited.",
        "kind: assembly",
        f"artifact: {artifact}",
        f"source-scroll: {phext_io.fmt(src_coord)}",
        f"source-sha256: {src_sha}",
        f"target: {target}",
        f"compiler: {compiler}",
        f"compiler-commit: {COMMIT}",
        f"compile-command: {cmd}",
        f"flags: {flags}",
        f"object-sha256: {sha(obj_raw)}",
        f"object-region-scroll: {phext_io.fmt(obj_coord)}",
        f"renderer: {renderer}",
        f"render-command: {render_cmd}",
        "render-note: TinyCC emits no assembly text (there is no -S); "
        "this listing is the recorded disassembler's rendering of the "
        "object phcc produced, with the renderer's leading build-host "
        "path normalized to the bare object name.",
        f"build-host: {HOST}",
        f"built-at: {BUILT_AT}",
        f"listing-sha256: {sha(body)}",
    ]
    return ("\n".join(hdr) + "\n\n").encode("utf-8") + body, body


def canonical(raw):
    return b"phext-binary:1:base64\n" + base64.b64encode(raw)


def main():
    base_bytes = open(BASE, "rb").read()
    scrolls = phext_io.load_phext(BASE)
    assert phext_io.implode(scrolls) == base_bytes, "base round-trip failed"
    assert sha(scrolls[LIBTCC1_SRC]) == OLD1
    out = dict(scrolls)
    log = {}

    # ---------- libtcc1.c Vol 2 + manifest + Vol 3 ----------
    path = "lib/libtcc1.c"
    data = open(os.path.join(FIXED, path), "rb").read()
    assert sha(data) == NEW1 and len(data) == 13067
    man = phext_io.parse_manifest(scrolls)
    assert man[path] == LIBTCC1_SRC
    out[LIBTCC1_SRC] = data
    mc = (1, 1, 1, 1, 2, 10, 1, 1, 1)
    lines = out[mc].decode().splitlines()
    hit = 0
    for i, l in enumerate(lines):
        if l.startswith(path + "\t"):
            p = l.split("\t")
            p[2], p[3] = sha(data), str(len(data))
            lines[i] = "\t".join(p)
            hit += 1
    assert hit == 1
    out[mc] = ("\n".join(lines) + "\n").encode()

    vol3 = json.load(open(os.path.join(R, "work/vol3_libtcc1.json")))[path]
    assert vol3["sha256"] == NEW1
    old_v3 = [c for c in out if c[:8] == (1, 1, 1, 4, 3, 7, 1, 2)]
    for c in old_v3:
        del out[c]
    for coord_s, b64 in vol3["scrolls"].items():
        out[phext_io.parse_coord(coord_s)] = base64.b64decode(b64)
    rc = (1, 1, 1, 1, 3, 10, 1, 1, 1)
    rlines = out[rc].decode().splitlines()
    rlines = splice_block(rlines, path, vol3["map_lines"])
    out[rc] = ("\n".join(rlines) + "\n").encode()
    dc = (1, 1, 1, 1, 3, 10, 1, 3, 1)
    dlines = out[dc].decode().splitlines()
    didx = [i for i, l in enumerate(dlines) if l.startswith(path + "\t")]
    assert len(didx) <= 1
    if vol3["reg_line"]:
        if didx:
            dlines[didx[0]] = vol3["reg_line"]
        else:
            dlines.append(vol3["reg_line"])
    elif didx:
        del dlines[didx[0]]
    out[dc] = ("\n".join(dlines) + "\n").encode()
    log[path] = {"vol3_old": len(old_v3), "vol3_new": len(vol3["scrolls"]),
                 "err_bytes": vol3["err_bytes"]}

    # ---------- phext.c/h Source scrolls + Sec 14 addendum ----------
    addendum = {}
    for pth, coord in (("phext/phext.c", PHEXTC_SRC), ("phext/phext.h", PHEXTH_SRC)):
        d = open(os.path.join(FIXED, pth), "rb").read()
        addendum[pth] = (sha(d), len(d))
        out[coord] = d
    ac = (1, 1, 1, 1, 2, 10, 1, 14, 1)
    alines = out[ac].decode().splitlines()
    for i, l in enumerate(alines):
        for pth, (h, sz) in addendum.items():
            if l.startswith(pth + "\t"):
                p = l.split("\t")
                p[2], p[3] = h, str(sz)
                alines[i] = "\t".join(p)
    alines.append("# re-issue (2026-11-07, F1 receipt re-issue pass): phext.c/h refreshed to the repo F4 bytes "
                  f"(phext.c {addendum['phext/phext.c'][0][:12]}... {addendum['phext/phext.c'][1]} B; "
                  f"phext.h {addendum['phext/phext.h'][0][:12]}... {addendum['phext/phext.h'][1]} B; "
                  "hashmap store, phcc commit e34c21f2 as carried in the tree at e399b212); "
                  "the phext object and its assembly listing were rebuilt from these bytes "
                  "(build register Sec 15; region manifest at Library 10000 root).")
    out[ac] = ("\n".join(alines) + "\n").encode()
    log["addendum"] = addendum

    # ---------- region objects ----------
    outdir = os.path.join(R, "work/out2")
    def rd(n):
        return open(os.path.join(outdir, n), "rb").read()
    objs = {
        (10000, 1, 1, 4, 2, 7, 1, 2, 1): rd("libtcc1-x86_64.o"),
        (10000, 1, 1, 4, 2, 7, 1, 2, 2): rd("libtcc1-arm64.o"),
        (10000, 1, 1, 4, 2, 7, 1, 2, 3): rd("libtcc1-x86_64.a"),
        (10000, 1, 1, 4, 2, 7, 1, 2, 4): rd("libtcc1-arm64.a"),
        (10000, 1, 1, 4, 2, 10, 10, 1, 1): rd("phext-x86_64.o"),
    }
    region_log = {}
    for coord, raw in objs.items():
        enc = canonical(raw)
        region_log[phext_io.fmt(coord)] = {
            "raw_sha256": sha(raw), "raw_size": len(raw),
            "scroll_changed": enc != scrolls[coord]}
        out[coord] = enc
    # the F1 claim, machine-checked here: libtcc1 scrolls unchanged
    for coord in list(objs)[:4]:
        assert not region_log[phext_io.fmt(coord)]["scroll_changed"], coord
    log["region"] = region_log

    # ---------- region root manifest ----------
    root = (10000, 1, 1, 1, 1, 1, 1, 1, 1)
    mtext = out[root].decode()
    mlines = mtext.splitlines()
    for i, l in enumerate(mlines):
        if l.startswith("compiler-commit:"):
            mlines[i] = f"compiler-commit: {COMMIT}"
        elif l.startswith("built-at:"):
            mlines[i] = f"built-at: {BUILT_AT}"
        elif l.startswith("entry\t"):
            p = l.split("\t")
            coord_s = p[1]
            raw = None
            for coord, r in objs.items():
                if phext_io.fmt(coord) == coord_s:
                    raw = r
            assert raw is not None, coord_s
            p[5] = str(len(raw))          # raw-size
            p[6] = sha(raw)               # raw-sha256
            p[8] = CC_ARM if p[4] == "arm64" else CC_X86   # compiler
            p[9] = COMMIT                 # compiler-commit
            p[12] = BUILT_AT              # built-at
            mlines[i] = "\t".join(p)
    mlines.append("# re-issue (2026-11-07, F1 receipt re-issue pass): all five artifacts rebuilt on aletheia-core "
                  "from the repo tree at e399b212 (libtcc1.c at its F1 bytes 69879e2a..., phext.c at its F4 bytes "
                  "cfdab3fd...). The four libtcc1 binaries are byte-identical to the previous build — the F1 cast "
                  "changes no emitted code, now verified on both backends — so their scrolls are unchanged; the "
                  "phext object differs (F4 hashmap store) and its scroll was replaced. Provenance fields updated.")
    out[root] = ("\n".join(mlines) + "\n").encode()

    # ---------- assembly listings ----------
    def old_body(coord):
        _h, _s, b = scrolls[coord].partition(b"\n\n")
        return b
    listings = [
        ((1, 1, 1, 3, 2, 7, 1, 2, 2), "lib/libtcc1.c", LIBTCC1_SRC, NEW1,
         "x86_64", CC_X86,
         "cd lib && ../tcc -c libtcc1.c -o libtcc1-x86_64.o " + XFLAGS,
         XFLAGS, RENDER_X86, "objdump -dr libtcc1-x86_64.o",
         (10000, 1, 1, 4, 2, 7, 1, 2, 1), objs[(10000, 1, 1, 4, 2, 7, 1, 2, 1)],
         rd("libtcc1-x86_64.s"), "libtcc1-x86_64.o"),
        ((1, 1, 1, 3, 2, 7, 1, 2, 3), "lib/libtcc1.c", LIBTCC1_SRC, NEW1,
         "arm64", CC_ARM,
         "cd lib && ../arm64-tcc -c libtcc1.c -o libtcc1-arm64.o " + XFLAGS,
         XFLAGS, RENDER_ARM, "llvm-objdump-18 -d -r libtcc1-arm64.o",
         (10000, 1, 1, 4, 2, 7, 1, 2, 2), objs[(10000, 1, 1, 4, 2, 7, 1, 2, 2)],
         rd("libtcc1-arm64.s"), "libtcc1-arm64.o"),
        ((1, 1, 1, 3, 2, 10, 10, 1, 2), "phext/phext.c", PHEXTC_SRC,
         addendum["phext/phext.c"][0], "x86_64", CC_X86,
         "./tcc -B. -c phext/phext.c -o phext-x86_64.o",
         "(none beyond -B.)", RENDER_X86, "objdump -dr phext-x86_64.o",
         (10000, 1, 1, 4, 2, 10, 10, 1, 1), objs[(10000, 1, 1, 4, 2, 10, 10, 1, 1)],
         rd("phext-x86_64.s"), "phext-x86_64.o"),
    ]
    for coord, art, src, ssha, tgt, cc, cmd, fl, rend, rcmd, oc, oraw, sbody, oname in listings:
        content, body = assembly_scroll(art, src, ssha, tgt, cc, cmd, fl,
                                        rend, rcmd, oc, oraw, sbody, oname)
        if art == "lib/libtcc1.c":
            assert body == old_body(coord), f"{art} {tgt}: listing body changed!"
        out[coord] = content
        log[f"listing {art} {tgt}"] = {"body_sha256": sha(body),
                                       "scroll_sha256": sha(content)}
    # ---------- build register (Sec 15) ----------
    reg = (1, 1, 1, 1, 2, 10, 1, 15, 1)
    rtext = out[reg].decode().splitlines()
    for i, l in enumerate(rtext):
        if l.startswith("compiler:"):
            rtext[i] = f"compiler: {CC_X86}"
        elif l.startswith("compiler-arm64:"):
            rtext[i] = f"compiler-arm64: {CC_ARM}"
        elif l.startswith("compiler-commit:"):
            rtext[i] = f"compiler-commit: {COMMIT}"
        elif l.startswith("built-at:"):
            rtext[i] = f"built-at: {BUILT_AT}"
    rtext.append("# re-issue (2026-11-07, F1 receipt re-issue pass): listings and region artifacts regenerated "
                 "from the repo tree at e399b212 (libtcc1.c F1 bytes; phext.c F4 bytes) — see the region "
                 "manifest's re-issue note and Meta Sec 22.")
    out[reg] = ("\n".join(rtext) + "\n").encode()

    # ---------- diff discipline ----------
    blob = phext_io.implode(out)
    with open(OUT, "wb") as f:
        f.write(blob)
    back = phext_io.load_phext(OUT)
    changed = [c for c in back if back[c] != scrolls.get(c)]
    added = [c for c in back if c not in scrolls]
    removed = [c for c in scrolls if c not in back]
    print(json.dumps(log, indent=1))
    print(f"stage1: {OUT} {len(blob)} B sha256 {sha(blob)}")
    print(f"scrolls {len(scrolls)} -> {len(back)}; changed {len(changed)} added {len(added)} removed {len(removed)}")
    for c in sorted(changed):
        print("  changed", phext_io.fmt(c), len(scrolls[c]), "->", len(back[c]))


if __name__ == "__main__":
    main()
