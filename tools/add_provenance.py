#!/usr/bin/env python3
"""add_provenance.py — consolidation stage 3: the lineage merge goes
on the record inside the phext itself, as a Meta scroll at
1.1.1/1.2.10/1.11.1 (Meta, Vol 2, Book 10, Ch 1, Sec 11 — the project
section after the Slice 3 register (Sec 8), the gate verdicts
(Sec 9) and the Slice 4 machine register (Sec 10)).

The scroll records: the two input lineages with full SHA-256, the
merge rule (A phases + B Vol 3), the full-diff proof counts, and
the Design-regeneration outcome. It deliberately does NOT carry
the final phext's own SHA-256 (a scroll cannot hash its container);
that hash lives in tools/README.md in wbic16/phcc and in
~/workspace/phcc-consolidated/REPORT.md.

Input: work/design.phext. Output: work/provenanced.phext. Verifies
the output differs from the input at exactly this one coordinate.
Stdlib only.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import phext_io

HOME = os.path.expanduser("~")
W = os.path.join(HOME, "workspace/phcc-consolidated")
COORD = (1, 1, 1, 1, 2, 10, 1, 11, 1)

TEXT = """# Consolidation provenance — Meta (Vol 2, Book 10), 2026-11-07
task: 39.7.9/6.5.8/4.4.9 (Will: "push and proceed")

This phext is the CONSOLIDATION of the two phcc lineages that grew
in parallel on 2026-11-07. The merge is recorded here so the
canonical file carries its own lineage.

inputs:
  A (phases): phcc-slice4/phcc.phext — Slice 0 Vol 1/2 + Slices 1-4
    phases (Tests/Design/Regressions/Proofs, gate v4 verdict) over
    importer-v3 Volume 3.
    sha256: de1ac0c6edcd33fcd082392ea8bbd28b17f5a6fdd7d8587cbf87211177f09eb1
    bytes: 30896709; scrolls: 27599
  B (members): phcc-importer-v4/phcc-fn.phext — same Vol 1/2 bytes,
    Volume 3 refined by importer v4 to 32933 members (7626
    functions, 2427 types, 22880 objects).
    sha256: bfdf93ed602415c954b990455ab57c3449dc8830b571e1c3bbecf98ae3566e76
    bytes: 31063540; scrolls: 52126

rule: A phases + B Vol 3. Every scroll with volume != 3 is taken
from A; every Volume 3 scroll is taken from B in full (the rebind
manifest at Meta Vol 3 Book 10 Sec 1 is therefore B's importer-v4
manifest, unmodified). v4 is a strict refinement of v3: all 17129
v3 members keep their exact addresses and payload hashes.

merge proof (full scroll-set diff, run twice — in memory and on
the written file; logs/merge-diff.json):
  non-Vol-3: 1952 scrolls from A, 0 missing, 0 extra, 0 differing
  Vol 3: 50828 scrolls from B, 0 missing, 0 extra, 0 differing
  A/B Vol 3 overlap: 25647 common coordinates, 25328 identical,
  319 differing (the v4 refinement: rewritten index scrolls of the
  109 rebuilt files, first gap pieces split in place, and the 3
  Meta Vol 3 scrolls); 25181 coordinates only in B; 0 only in A.

design regeneration (Slice 3's extract_design.py, unmodified, over
the merged phext; logs/view-diff.json):
  351 generated views regenerated against v4 members.
  196 byte-identical to lineage A's views.
  109 changed because the file's own members digest changed —
  exactly importer v4's files_rebuilt set (109/109 set-equal).
  46 changed with their own Source/members bindings unchanged:
  the tree-wide function/object name universes grew, so the
  extractor's calls / globals-referenced / cross-file edge
  sections resolve names that v3 left in gap segments.
  0 changed for any other reason. The section A.2 pipeline view
  regenerated byte-identical and still passes check_pipeline.py
  (17 names, 16 edges, 0 mismatches). Types recovered from gap
  segments by the extractor's labelled scan: 723 in A's views,
  2 now — the rest are first-class v4 members.
  The Design register (Meta Sec 8) was regenerated by the same
  run; it records the merged phext as its base.

after this scroll: gate v4.0.0 was re-run; its verdict at Meta
Sec 9 covers this phext including this scroll. The consolidated
file's own SHA-256 is recorded outside itself: tools/README.md
in wbic16/phcc and phcc-consolidated/REPORT.md.
"""


def main():
    src = os.path.join(W, "work/design.phext")
    dst = os.path.join(W, "work/provenanced.phext")
    scrolls = phext_io.load_phext(src)
    existing = scrolls.get(COORD)
    assert not existing, (f"{phext_io.fmt(COORD)} already carries "
                          f"{len(existing)} bytes — refusing to overwrite")
    out = dict(scrolls)
    out[COORD] = TEXT.encode()
    blob = phext_io.implode(out)
    with open(dst, "wb") as f:
        f.write(blob)
    back = phext_io.load_phext(dst)
    diffs = [k for k in set(back) | set(scrolls)
             if back.get(k) != scrolls.get(k)]
    assert diffs == [COORD], f"unexpected diffs: {diffs[:5]}"
    import hashlib
    print(f"provenance scroll placed at {phext_io.fmt(COORD)} "
          f"({len(TEXT.encode())} bytes)")
    print(f"output: {dst}  {len(blob)} bytes  "
          f"sha256 {hashlib.sha256(blob).hexdigest()}")
    print("diff vs input: exactly the provenance coordinate")


if __name__ == "__main__":
    main()
